package com.rumi.notification.infrastructure.web.dto;

import com.rumi.notification.domain.model.AlertSeverity;
import com.rumi.notification.domain.model.AlertStatus;
import com.rumi.notification.domain.model.AlertType;
import io.swagger.v3.oas.annotations.media.Schema;

import java.time.Instant;
import java.util.UUID;

@Schema(name = "AlertResponse", description = "An alert about a building")
public record AlertResponseDto(
        @Schema(description = "Identifier generated by the service", example = "0b7e4c2a-9d1f-4e3b-8a6c-5f2d1e0c9b8a")
        UUID id,
        @Schema(description = "Building the alert is about", example = "7a9b3c1d-2e4f-4b6a-8c0d-1e2f3a4b5c6d")
        UUID buildingId,
        @Schema(description = "SEISMIC_RISK when raised by a risk index, THRESHOLD_EXCEEDED when raised by a reading",
                example = "SEISMIC_RISK")
        AlertType type,
        @Schema(description = "LOW, MEDIUM, HIGH or CRITICAL", example = "CRITICAL")
        AlertSeverity severity,
        @Schema(description = "OPEN, ACKNOWLEDGED or RESOLVED", example = "OPEN")
        AlertStatus status,
        @Schema(description = "Short title of the alert", example = "Seismic risk CRITICAL")
        String title,
        @Schema(description = "Instructions for the residents and the administrator",
                example = "Critical structural risk after the seismic event. "
                        + "Evacuate the building now using the nearest evacuation route.")
        String message,
        @Schema(description = "True when the residents must evacuate (CRITICAL seismic risk, US16)", example = "true")
        boolean evacuationRequired,
        @Schema(description = "Risk index of Seismic Correlation that raised the alert; null for threshold alerts",
                example = "3c9a1e7d-4b2f-4d8e-a6c1-7e5f3b2d1a90", nullable = true)
        UUID riskIndexId,
        @Schema(description = "Seismic event reported by the IGP; null for threshold alerts",
                example = "9e8d7c6b-5a4f-4e3d-b2c1-0a9f8e7d6c5b", nullable = true)
        UUID seismicEventId,
        @Schema(description = "Sensor whose reading raised the alert; null for seismic risk alerts",
                example = "5d1c2f0e-8f4a-4a53-9a7e-0f3b1c9d7a11", nullable = true)
        UUID sensorId,
        @Schema(description = "Zone of the sensor; null for seismic risk alerts", example = "FLOOR-3-NORTH",
                nullable = true)
        String zone,
        @Schema(description = "Reading that exceeded the threshold; null for seismic risk alerts", example = "0.12",
                nullable = true)
        Double measuredValue,
        @Schema(description = "When the risk was calculated or the reading was recorded (UTC)",
                example = "2026-10-06T14:32:00Z")
        Instant occurredAt,
        @Schema(description = "When the alert was raised (UTC)", example = "2026-10-06T14:32:05Z")
        Instant createdAt,
        @Schema(description = "When the alert was acknowledged (UTC)", nullable = true)
        Instant acknowledgedAt,
        @Schema(description = "User who acknowledged the alert", nullable = true)
        UUID acknowledgedBy,
        @Schema(description = "When the alert was resolved (UTC)", nullable = true)
        Instant resolvedAt
) {
}
